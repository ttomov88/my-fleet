const LANGS = ["bg", "en"];
let LANG = "bg";
try {
  const saved = JSON.parse(localStorage.getItem("fleetlog_settings_v1") || "{}").lang;
  if (LANGS.includes(saved)) LANG = saved;
} catch (e) {}

function t(key, params) {
  const v = (I18N[LANG] && I18N[LANG][key] !== undefined) ? I18N[LANG][key] : I18N.en[key];
  if (v === undefined) return key;
  return typeof v === "function" ? v(params || {}) : v;
}
// Locale for dates: Bulgarian or English (UK style: 5 Dec 2026).
function locale() { return LANG === "bg" ? "bg-BG" : "en-GB"; }

// Fills every element marked data-i18n (text) / data-i18n-aria (aria-label) in the page.
function applyStaticText() {
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach(e => { e.textContent = t(e.dataset.i18n, e.dataset.n ? { n: +e.dataset.n } : undefined); });
  document.querySelectorAll("[data-i18n-aria]").forEach(e => e.setAttribute("aria-label", t(e.dataset.i18nAria)));
}
